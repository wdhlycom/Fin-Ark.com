#!/usr/bin/env node
// gen-articles.mjs
// 把 content/<lang>/*.md 自动转成 src/i18n/generatedArticles<lang>.ts
// 零依赖：自带最小 YAML frontmatter 解析 + Markdown 小节解析
//
// 用法：
//   node scripts/gen-articles.mjs            # 生成 content/ 下所有语言
//   node scripts/gen-articles.mjs zh         # 只生成中文
//   npm run gen:articles                     # 等价于上者（全部语言）
// 构建时会自动先跑一次（"build": "... && vite build"），无需手动。

import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT_DIR = join(ROOT, 'content');
const OUT_DIR = join(ROOT, 'src', 'i18n');

// ---------- 1. 解析 YAML frontmatter（仅支持 key: value 平铺） ----------
function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) return { hasFm: false, data: {}, body: text };
  const data = {};
  for (const raw of m[1].split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    let val = line.slice(idx + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    data[key] = val;
  }
  return { hasFm: true, data, body: text.slice(m[0].length) };
}

// ---------- 2. Markdown 正文 -> [{ h, p }] ----------
// 规则：任何 #~###### 行作为小节标题(h)；其下文本原样保留为该小节正文(p)。
// 首个标题之前的引文/导语(金句)也会保留为一篇 h:'' 的开篇小节，避免被丢弃。
// ArticlePage 现用 react-markdown 渲染 p，故此处【保留】Markdown 原文
// （段落间空行、列表、加粗、链接、引用等均原样输出），仅裁掉首尾空白。
function cleanParagraph(text) {
  return text.replace(/^\s+|\s+$/g, '');
}
function parseBody(body) {
  const sections = [];
  let head = null;
  let buf = [];
  const flush = () => {
    if (!buf.length) return;
    sections.push({ h: head ?? '', p: cleanParagraph(buf.join('\n')) });
  };
  for (const line of body.split('\n')) {
    const hm = line.match(/^#{1,6}\s+(.*?)\s*$/);
    if (hm) {
      flush();
      head = hm[1].trim();
      buf = [];
    } else {
      buf.push(line);
    }
  }
  flush();
  return sections;
}

// ---------- 3. 读取某语言目录下全部 .md ----------
function buildLang(lang) {
  const dir = join(CONTENT_DIR, lang);
  if (!existsSync(dir)) return null;
  const files = readdirSync(dir).filter(
    (f) => f.endsWith('.md') && !f.startsWith('_') && f !== 'README.md'
  );
  const grouped = {};
  const usedIds = new Set();
  for (const f of files) {
    const raw = readFileSync(join(dir, f), 'utf8');
    const { hasFm, data, body } = parseFrontmatter(raw);
    if (!hasFm || !data.section) {
      console.warn(`  ⚠ 跳过 ${lang}/${f}：缺少 \`---\` frontmatter 或 section 字段`);
      continue;
    }
    const section = data.section;
    let id = data.id || `gen-${section}-${f.replace(/\.md$/, '')}`;
    if (usedIds.has(id)) id = `${id}-${usedIds.size}`;
    usedIds.add(id);
    const pin = data.pin === 'true' || data.pin === '1';
    const order = data.order ? Number(data.order) : undefined;
    const article = {
      id,
      title: data.title || f.replace(/\.md$/, ''),
      subtitle: data.subtitle || '',
      date: data.date || '1970-01-01',
      summary: data.summary || '',
      pin,
      order,
      category: data.category || undefined,
      body: parseBody(body),
    };
    if (!article.body.length) console.warn(`  ⚠ ${lang}/${f}：正文没有 ## 小节，body 为空`);
    (grouped[section] ||= []).push(article);
  }
  // 同板块内按日期倒序（新 -> 旧）
  for (const k of Object.keys(grouped)) {
    grouped[k].sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));
  }
  return grouped;
}

// ---------- 4. 写出 TS 文件 ----------
function emit(lang, grouped) {
  if (!grouped) {
    console.log(`· ${lang}: 无 content/${lang}/ 目录，跳过`);
    return;
  }
  const suffix = lang === 'zh' ? '' : `.${lang}`;
  const objName = `GENERATED_ARTICLES${suffix ? '_' + lang : ''}`;
  // 输出文件名用 .gen 后缀，避免被 IDE 锁定的旧 generatedArticles.ts 占用导致写入失败
  const outFile = join(OUT_DIR, `generatedArticles.gen${suffix}.ts`);
  const total = Object.values(grouped).reduce((n, arr) => n + arr.length, 0);
  const fileText =
    `// AUTO-GENERATED by scripts/gen-articles.mjs — 不要手动编辑\n` +
    `// 来源：content/${lang}/*.md\n` +
    `import type { Article } from './types';\n\n` +
    `export const ${objName}: Record<string, Article[]> = ${JSON.stringify(grouped, null, 2)};\n`;
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(outFile, fileText, 'utf8');
  console.log(`✓ ${lang}: ${outFile}（${total} 篇 / ${Object.keys(grouped).length} 个板块）`);
}

// ---------- 5. 入口 ----------
const args = process.argv.slice(2);
let targetLangs = args;
if (!targetLangs.length) {
  targetLangs = existsSync(CONTENT_DIR)
    ? readdirSync(CONTENT_DIR).filter((d) => existsSync(join(CONTENT_DIR, d)))
    : [];
}
for (const lang of targetLangs) emit(lang, buildLang(lang));
console.log('管线完成。\n');
